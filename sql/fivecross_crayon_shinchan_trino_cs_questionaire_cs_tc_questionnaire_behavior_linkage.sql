    WHERE v."$part_event" = 'new_role'
      AND v."$part_date" BETWEEN '2026-07-29' AND '2026-07-31'
    GROUP BY 1
),
LoginDays AS (
    SELECT DISTINCT m.role_id, DATE(v."$part_date") AS login_date
    FROM MatchedRoles m
    INNER JOIN ta.v_event_18 v ON v."#user_id" = m.user_id
    WHERE v."$part_event" = 'login'
      AND v."$part_date" BETWEEN '2026-07-29' AND '2026-07-31'
),
EventGaps AS (
    SELECT m.role_id, DATE(v."$part_date") AS event_date,
        DATE_DIFF('second', CAST(v."#event_time" AS TIMESTAMP),
            LEAD(CAST(v."#event_time" AS TIMESTAMP)) OVER (
                PARTITION BY m.role_id, DATE(v."$part_date") ORDER BY v."#event_time")) AS next_gap_seconds
    FROM MatchedRoles m
    INNER JOIN ta.v_event_18 v ON v."#user_id" = m.user_id
    WHERE v."$part_date" BETWEEN '2026-07-29' AND '2026-07-31'
      AND v."#event_name" NOT LIKE '%app%'
),
OnlineMinutes AS (
    SELECT role_id, SUM(CASE WHEN next_gap_seconds BETWEEN 0 AND 119 THEN next_gap_seconds ELSE 0 END) / 60.0 AS online_minutes
    FROM EventGaps GROUP BY 1
),
Payments AS (
    SELECT m.role_id, SUM(TRY_CAST(v.pay_amount AS DOUBLE) / COALESCE(x.exchange, 1)) AS revenue_usd,
        COUNT(*) AS payment_orders
    FROM MatchedRoles m
    INNER JOIN ta.v_event_18 v ON v."#user_id" = m.user_id
    LEFT JOIN ta_dim.ta_exchange x ON v."$part_date" = x.ex_date AND v.pay_currency = x.currency
    WHERE v."$part_event" = 'charge'
      AND v."$part_date" BETWEEN '2026-07-29' AND '2026-07-31'
      AND (v.sandbox IS NULL OR v.sandbox = FALSE)
      AND (v.is_freebuy IS NULL OR v.is_freebuy = FALSE)
    GROUP BY 1
),
MainStage AS (
    SELECT m.role_id, MAX(TRY_CAST(v.a_rst[1].id AS BIGINT)) AS max_main_stage_id
    FROM MatchedRoles m
    INNER JOIN ta.v_event_18 v ON v."#user_id" = m.user_id
    WHERE v."#event_name" = 'stage_fight'
      AND v."$part_date" BETWEEN '2026-07-29' AND '2026-07-31'
      AND CAST(v.a_rst[1].key AS INTEGER) = 1001
    GROUP BY 1
),
RoleMetrics AS (
    SELECT s.*, m.user_id, c.reg_date, o.online_minutes, p.revenue_usd, p.payment_orders, st.max_main_stage_id,
        CASE WHEN l1.role_id IS NOT NULL THEN 1 ELSE 0 END AS retained_d1,
        CASE WHEN l2.role_id IS NOT NULL THEN 1 ELSE 0 END AS retained_d2
    FROM SurveyRoleTags s
    LEFT JOIN MatchedRoles m ON s.role_id = m.role_id
    LEFT JOIN RoleCohort c ON s.role_id = c.role_id
    LEFT JOIN OnlineMinutes o ON s.role_id = o.role_id
    LEFT JOIN Payments p ON s.role_id = p.role_id
    LEFT JOIN MainStage st ON s.role_id = st.role_id
    LEFT JOIN LoginDays l1 ON s.role_id = l1.role_id AND l1.login_date = DATE_ADD('day', 1, c.reg_date)
    LEFT JOIN LoginDays l2 ON s.role_id = l2.role_id AND l2.login_date = DATE_ADD('day', 2, c.reg_date)
),
ExpandedTags AS (
    SELECT role_id, '菇勇者经历' AS tag_dimension, lom AS tag_value FROM RoleMetrics WHERE lom IS NOT NULL
    UNION ALL SELECT role_id, '最想体验内容', tag FROM RoleMetrics CROSS JOIN UNNEST(SPLIT(desired, ' | ')) AS t(tag) WHERE desired IS NOT NULL
    UNION ALL SELECT role_id, '常玩游戏类型', tag FROM RoleMetrics CROSS JOIN UNNEST(SPLIT(game_type, ' | ')) AS t(tag) WHERE game_type IS NOT NULL
    UNION ALL SELECT role_id, 'Day2自报付费', day2_pay FROM RoleMetrics WHERE day2_pay IS NOT NULL
    UNION ALL SELECT role_id, '未来付费意向', future_pay FROM RoleMetrics WHERE future_pay IS NOT NULL
    UNION ALL SELECT role_id, '持续游玩意向', continue_intent FROM RoleMetrics WHERE continue_intent IS NOT NULL
)
SELECT
    e.tag_dimension AS "标签维度", e.tag_value AS "标签", COUNT(DISTINCT e.role_id) AS "问卷角色数",
    COUNT(DISTINCT r.user_id) AS "行为匹配角色数",
    ROUND(100.0 * COUNT(DISTINCT r.user_id) / NULLIF(COUNT(DISTINCT e.role_id), 0), 2) AS "匹配率(%)",
    COUNT(DISTINCT r.role_id) FILTER (WHERE r.reg_date IS NOT NULL) AS "创角角色数",
    COUNT(DISTINCT r.role_id) FILTER (WHERE DATE_ADD('day', 1, r.reg_date) <= DATE '2026-07-31') AS "D1成熟样本",
    ROUND(100.0 * AVG(CASE WHEN DATE_ADD('day', 1, r.reg_date) <= DATE '2026-07-31' THEN r.retained_d1 END), 2) AS "D1留存率(%)",
    COUNT(DISTINCT r.role_id) FILTER (WHERE DATE_ADD('day', 2, r.reg_date) <= DATE '2026-07-31') AS "D2成熟样本",
    ROUND(100.0 * AVG(CASE WHEN DATE_ADD('day', 2, r.reg_date) <= DATE '2026-07-31' THEN r.retained_d2 END), 2) AS "D2留存率(%)",
    ROUND(100.0 * AVG(CASE WHEN COALESCE(r.revenue_usd, 0) > 0 THEN 1.0 ELSE 0.0 END), 2) AS "累计付费率(%)",
    ROUND(SUM(COALESCE(r.revenue_usd, 0)) / NULLIF(COUNT(DISTINCT r.role_id), 0), 4) AS "累计LTV(USD)",
    ROUND(AVG(NULLIF(r.online_minutes, 0)), 2) AS "平均在线分钟", ROUND(AVG(r.max_main_stage_id), 1) AS "平均最高主线关卡ID"
FROM ExpandedTags e
LEFT JOIN RoleMetrics r ON e.role_id = r.role_id
GROUP BY 1, 2
ORDER BY 1, "问卷角色数" DESC, 2;
